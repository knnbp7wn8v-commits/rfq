-- Az itt felvett értékek az éles export (mydb_backup.sql) tényleges
-- tartalmával egyeznek. A forrás export egyéb táblái (customers, addresses,
-- cart, rfq) személyes adatot (valós ügyfél-email/telefon, jelszó-hash)
-- tartalmaznak, ezért ebbe a migrációba szándékosan NEM kerültek át - a
-- fenti táblák viszont kizárólag termék-/technikai paramétereket
-- tartalmaznak, személyes adatot nem.
--
